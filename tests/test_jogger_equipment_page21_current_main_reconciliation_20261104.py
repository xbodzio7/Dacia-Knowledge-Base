from __future__ import annotations
import json
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "data/reporting/jogger_equipment_page21_current_main_reconciliation_20261104.json"

@unittest.skipUnless(REPORT.exists(), "generated by the temporary current-main reconciliation workflow")
class JoggerPage21CurrentMainReconciliation20261104Test(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.report = json.loads(REPORT.read_text(encoding="utf-8"))

    def test_exact_current_main_reconciliation(self) -> None:
        report = self.report
        self.assertEqual(report["status"], "complete_no_new_import")
        self.assertEqual(report["scope"]["unique_selected_record_codes"], 30)
        self.assertEqual(report["scope"]["selected_record_codes_already_present_in_current_main"], 30)
        self.assertEqual(report["scope"]["missing_selected_record_codes"], 0)
        self.assertEqual(report["scope"]["unresolved_candidates"], 72)
        self.assertTrue(report["summary"]["all_selected_observations_already_present"])
        self.assertTrue(report["summary"]["no_exact_import_ready_gap"])
        self.assertEqual(report["summary"]["master_data_changes"], 0)
        self.assertEqual(report["summary"]["import_specs_added"], 0)

    def test_every_selected_record_is_reported_as_present(self) -> None:
        records = self.report["selected_evidence_records"]
        self.assertEqual(len(records), 30)
        self.assertEqual({row["current_main_presence"] for row in records}, {"present"})
        self.assertEqual(len({row["record_code"] for row in records}), 30)
        self.assertTrue(all(row["attribute_code"] == "heated_steering_wheel" for row in records))

    def test_journey_conflict_remains_deferred(self) -> None:
        self.assertEqual(self.report["summary"]["review_decisions"], {"deferred_source_conflict": 1})
        self.assertEqual(self.report["source"]["page"], 21)
        self.assertEqual(len(self.report["current_main"]["sha"]), 40)

if __name__ == "__main__":
    unittest.main()
